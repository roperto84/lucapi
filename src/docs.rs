#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::{Assertion, AssertKind, Folder, KV, Method};

    fn workspace() -> ProjectData {
        let mut folder = Folder::new("Users");
        let mut request = ApiRequest::new("List <users>", Method::Get, "{{baseUrl}}/users");
        request.description = "Returns users & their roles".into();
        request.params.push(KV::pair("page", "1"));
        let mut auth = KV::pair("Authorization", "Bearer super-secret-token");
        auth.secret = true;
        request.headers.push(auth);
        request.headers.push(KV::pair("Accept", "application/json"));
        request.assertions.push(Assertion {
            enabled: true,
            kind: AssertKind::StatusEquals,
            target: String::new(),
            expected: "200".into(),
        });
        request.example_status = 200;
        request.example_body = "{\"users\":[{\"id\":1}]}".into();
        folder.requests.push(request);
        let mut data: ProjectData = serde_json::from_str(
            "{\"name\":\"Demo\",\"folders\":[],\"envs\":[],\"active_env\":null,\"history\":[],\"settings\":{\"dark\":true,\"timeout_ms\":15000,\"follow_redirects\":true,\"line_numbers\":true,\"mock_port\":4010},\"session\":{}}",
        )
        .expect("workspace");
        data.folders = vec![folder];
        data
    }

    #[test]
    fn escapes_names_and_descriptions() {
        let site = build(&workspace(), &Options::default());
        assert!(site.html.contains("List &lt;users&gt;"));
        assert!(site.html.contains("Returns users &amp; their roles"));
        assert!(!site.html.contains("<users>"));
    }

    #[test]
    fn never_publishes_secret_header_values() {
        let site = build(&workspace(), &Options::default());
        assert!(!site.html.contains("super-secret-token"));
        assert!(site.html.contains("••••"));
    }

    #[test]
    fn renders_structure_and_share_links() {
        let options = Options {
            base_url: "https://docs.example.com/api/".into(),
            ..Options::default()
        };
        let site = build(&workspace(), &options);
        assert_eq!(site.requests, 1);
        assert_eq!(site.anchors.len(), 1);
        let (anchor, name) = &site.anchors[0];
        assert_eq!(name, "List <users>");
        assert!(site.html.contains(&format!("id=\"{anchor}\"")));
        assert!(site.html.contains("data-base=\"https://docs.example.com/api\""));
        assert!(site.html.contains("Example response"));
        assert!(site.html.contains("application/json"));
    }

    #[test]
    fn options_control_what_is_included() {
        let options = Options {
            include_examples: false,
            include_bodies: false,
            include_auth: false,
            dark: false,
            ..Options::default()
        };
        let site = build(&workspace(), &options);
        assert!(!site.html.contains("Example response"));
        assert!(!site.html.contains("theme-dark"));
        assert!(site.html.contains("theme-light"));
    }

    #[test]
    fn variables_are_resolved_unless_disabled() {
        let mut data = workspace();
        data.envs.push(
            serde_json::from_str(
                "{\"id\":7,\"name\":\"Local\",\"vars\":[{\"enabled\":true,\"key\":\"baseUrl\",\"value\":\"https://api.local/v1\",\"desc\":\"\",\"secret\":false}]}",
            )
            .unwrap(),
        );
        data.active_env = Some(data.envs[0].id);
        let resolved = build(&data, &Options::default());
        assert!(resolved.html.contains("https://api.local/v1/users"));
        assert!(!resolved.html.contains("{{baseUrl}}"));

        let raw = build(
            &data,
            &Options {
                resolve_variables: false,
                ..Options::default()
            },
        );
        assert!(raw.html.contains("{{baseUrl}}/users"));
    }

    #[test]
    fn anchors_are_unique_for_duplicate_names() {
        let mut data = workspace();
        let mut copy = data.folders[0].requests[0].clone();
        copy.id = crate::model::next_id();
        data.folders[0].requests.push(copy);
        let site = build(&data, &Options::default());
        assert_eq!(site.anchors.len(), 2);
        assert_ne!(site.anchors[0].0, site.anchors[1].0);
    }

    #[test]
    fn secret_environment_values_are_redacted() {
        let mut data = workspace();
        let mut env: crate::model::Environment = serde_json::from_str(
            "{\"id\":1,\"name\":\"Prod\",\"vars\":[{\"enabled\":true,\"key\":\"token\",\"value\":\"do-not-leak-me\",\"desc\":\"\",\"secret\":true}]}",
        )
        .unwrap();
        env.vars[0].secret = true;
        data.envs.push(env);
        data.folders[0].requests[0].description = "Uses do-not-leak-me here".into();
        let site = build(&data, &Options::default());
        assert!(!site.html.contains("do-not-leak-me"));
        assert!(site.html.contains("Uses •••• here"));
    }
}
