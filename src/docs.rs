//! Static, self-contained documentation site generated from a workspace.
//!
//! The output is a single `index.html` with no external assets, so it can be
//! published anywhere (a repo, an internal static host, a zip shared with a
//! client). Secrets are redacted before anything is written.

use crate::model::{ApiRequest, Auth, BodyMode, Environment, KV, ProjectData};

#[derive(Clone, Debug)]
pub struct Options {
    pub title: String,
    pub intro: String,
    /// Absolute URL the site will live at; used to build shareable links.
    pub base_url: String,
    pub include_examples: bool,
    pub include_bodies: bool,
    pub include_auth: bool,
    pub dark: bool,
    /// Replace `{{variables}}` with the active environment values.
    pub resolve_variables: bool,
}

impl Default for Options {
    fn default() -> Self {
        Self {
            title: String::new(),
            intro: String::new(),
            base_url: String::new(),
            include_examples: true,
            include_bodies: true,
            include_auth: true,
            dark: true,
            resolve_variables: true,
        }
    }
}

pub struct Site {
    pub html: String,
    pub requests: usize,
    /// `(anchor, display name)` for every published request.
    pub anchors: Vec<(String, String)>,
}

/// Anchor of every request, mirroring what `build` produces.
pub fn anchors(data: &ProjectData) -> Vec<(crate::model::Id, String)> {
    let mut used: Vec<String> = Vec::new();
    let mut out = Vec::new();
    for folder in &data.folders {
        for request in &folder.requests {
            out.push((request.id, unique_anchor(request, &mut used)));
        }
    }
    out
}

pub fn build(data: &ProjectData, options: &Options) -> Site {
    let title = if options.title.trim().is_empty() {
        format!("{} API", data.name)
    } else {
        options.title.trim().to_string()
    };
    let secrets = collect_secrets(data);
    let variables = if options.resolve_variables {
        data.env_map()
    } else {
        Default::default()
    };
    let redact = |text: &str| redact_text(&resolve(text, &variables), &secrets);

    let mut anchors: Vec<(String, String)> = Vec::new();
    let mut used: Vec<String> = Vec::new();
    let mut body = String::new();
    let mut count = 0usize;

    for folder in &data.folders {
        if folder.requests.is_empty() {
            continue;
        }
        body.push_str(&format!(
            "<section class=\"collection\">\n<h2>{}</h2>\n",
            escape(&redact(&folder.name))
        ));
        if options.include_auth && !matches!(folder.auth, Auth::None | Auth::Inherit) {
            body.push_str(&format!(
                "<p class=\"collection-auth\">Collection auth: {}</p>\n",
                escape(&auth_label(&folder.auth))
            ));
        }
        for request in &folder.requests {
            count += 1;
            let anchor = unique_anchor(request, &mut used);
            anchors.push((anchor.clone(), request.name.clone()));
            body.push_str(&request_html(request, &anchor, options, &redact));
        }
        body.push_str("</section>\n");
    }

    let navigation: String = anchors
        .iter()
        .map(|(anchor, name)| {
            format!(
                "<a class=\"nav-link\" href=\"#{}\" data-search=\"{}\">{}</a>\n",
                anchor,
                escape(&name.to_lowercase()),
                escape(name)
            )
        })
        .collect();

    let endpoints_label = if count == 1 {
        "1 endpoint".to_string()
    } else {
        format!("{count} endpoints")
    };
    let intro = if options.intro.trim().is_empty() {
        format!(
            "Reference for every request in the {} workspace.",
            escape(&data.name)
        )
    } else {
        escape(options.intro.trim())
    };
    let share_base = options.base_url.trim().trim_end_matches('/').to_string();

    let html = format!(
        r#"<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="generator" content="LucAPI {version}">
<title>{title}</title>
<style>{style}</style>
</head>
<body class="{theme}">
<header class="top">
  <div class="brand">
    <span class="logo" aria-hidden="true">{logo}</span>
    <div>
      <h1>{title}</h1>
      <p class="intro">{intro}</p>
    </div>
  </div>
  <div class="meta">
    <span class="pill">{endpoints_label}</span>
    <span class="pill">{collections} collections</span>
  </div>
</header>
<div class="layout">
  <nav class="sidebar">
    <input id="search" type="search" placeholder="Filter endpoints" autocomplete="off" spellcheck="false">
    <div class="nav" id="nav">{navigation}</div>
    <p class="hint">Read-only reference. Generated by LucAPI.</p>
  </nav>
  <main id="content">
{body}  </main>
</div>
<footer class="foot">
  <span>Generated with LucAPI {version}</span>
  <span>{updated}</span>
</footer>
<script>
(function () {{
  var input = document.getElementById('search');
  var links = Array.prototype.slice.call(document.querySelectorAll('.nav-link'));
  var sections = Array.prototype.slice.call(document.querySelectorAll('.request'));
  var empty = document.createElement('p');
  empty.className = 'nav-empty';
  empty.textContent = 'No endpoint matches.';
  input.addEventListener('input', function () {{
    var needle = input.value.trim().toLowerCase();
    var shown = 0;
    links.forEach(function (link) {{
      var text = link.getAttribute('data-search') + ' ' + link.textContent.toLowerCase();
      var match = !needle || text.indexOf(needle) !== -1;
      link.style.display = match ? '' : 'none';
      if (match) {{ shown += 1; }}
    }});
    sections.forEach(function (section) {{
      var title = section.getAttribute('data-search') || '';
      section.style.display = !needle || title.indexOf(needle) !== -1 ? '' : 'none';
    }});
    if (needle && shown === 0) {{
      if (!empty.parentNode) {{ document.getElementById('nav').appendChild(empty); }}
    }} else if (empty.parentNode) {{
      empty.parentNode.removeChild(empty);
    }}
  }});
  document.querySelectorAll('.copy').forEach(function (button) {{
    button.addEventListener('click', function () {{
      var base = button.getAttribute('data-base') || '';
      var file = location.pathname.split('/').pop() || 'index.html';
      var url = base ? base + '/' + file + '#' + button.getAttribute('data-anchor')
                     : file + '#' + button.getAttribute('data-anchor');
      var label = button.textContent;
      var done = function () {{
        button.textContent = 'Copied';
        setTimeout(function () {{ button.textContent = label; }}, 1400);
      }};
      if (navigator.clipboard) {{
        navigator.clipboard.writeText(url).then(done, done);
      }} else {{
        done();
      }}
    }});
  }});
}})();
</script>
</body>
</html>
"#,
        version = env!("CARGO_PKG_VERSION"),
        title = escape(&title),
        intro = intro,
        logo = LOGO,
        endpoints_label = endpoints_label,
        collections = data
            .folders
            .iter()
            .filter(|folder| !folder.requests.is_empty())
            .count(),
        navigation = navigation,
        body = body,
        updated = escape(&today()),
        style = STYLE,
        theme = if options.dark { "theme-dark" } else { "theme-light" },
    );

    Site {
        html: html.replace("data-base=\"\"", &format!("data-base=\"{share_base}\"")),
        requests: count,
        anchors,
    }
}

fn request_html(
    request: &ApiRequest,
    anchor: &str,
    options: &Options,
    redact: &impl Fn(&str) -> String,
) -> String {
    let mut out = String::new();
    let url_text = redact(&request.url);
    let search = format!(
        "{} {} {}",
        request.name.to_lowercase(),
        request.method.as_str().to_lowercase(),
        url_text.to_lowercase()
    );
    out.push_str(&format!(
        "<article class=\"request\" id=\"{anchor}\" data-search=\"{}\">\n",
        escape(&search)
    ));
    out.push_str("<div class=\"request-head\">\n");
    out.push_str(&format!(
        "<span class=\"method m-{}\">{}</span>\n",
        request.method.as_str().to_lowercase(),
        request.method.as_str()
    ));
    out.push_str(&format!(
        "<h3>{}</h3>\n<button class=\"copy\" data-anchor=\"{anchor}\" data-base=\"\">Copy link</button>\n",
        escape(&redact(&request.name))
    ));
    out.push_str("</div>\n");

    if !request.description.trim().is_empty() {
        out.push_str(&format!(
            "<p class=\"desc\">{}</p>\n",
            escape(&redact(&request.description))
        ));
    }

    out.push_str(&format!(
        "<div class=\"endpoint\"><span class=\"method small m-{}\">{}</span><code>{}</code></div>\n",
        request.method.as_str().to_lowercase(),
        request.method.as_str(),
        escape(&url_text)
    ));

    if options.include_auth {
        let auth = if matches!(request.auth, Auth::Inherit) {
            "Inherited from the collection".to_string()
        } else {
            auth_label(&request.auth)
        };
        out.push_str(&format!(
            "<p class=\"meta-line\"><strong>Auth</strong> {}</p>\n",
            escape(&auth)
        ));
    }

    let params: Vec<&KV> = request.params.iter().filter(|kv| kv.enabled).collect();
    if !params.is_empty() {
        out.push_str("<h4>Query parameters</h4>\n<table>\n<thead><tr><th>Name</th><th>Value</th><th>Description</th></tr></thead>\n<tbody>\n");
        for kv in params {
            out.push_str(&format!(
                "<tr><td><code>{}</code></td><td>{}</td><td>{}</td></tr>\n",
                escape(&kv.key),
                escape(&redact(&kv.value)),
                escape(&redact(&kv.desc))
            ));
        }
        out.push_str("</tbody>\n</table>\n");
    }

    let headers: Vec<&KV> = request.headers.iter().filter(|kv| kv.enabled).collect();
    if !headers.is_empty() {
        out.push_str("<h4>Headers</h4>\n<table>\n<thead><tr><th>Name</th><th>Value</th><th>Description</th></tr></thead>\n<tbody>\n");
        for kv in headers {
            let value = if kv.secret {
                "••••".to_string()
            } else {
                redact(&kv.value)
            };
            out.push_str(&format!(
                "<tr><td><code>{}</code></td><td>{}</td><td>{}</td></tr>\n",
                escape(&kv.key),
                escape(&value),
                escape(&kv.desc)
            ));
        }
        out.push_str("</tbody>\n</table>\n");
    }

    if options.include_bodies {
        match request.body_mode {
            BodyMode::Json | BodyMode::Text => {
                if !request.body.trim().is_empty() {
                    out.push_str(&format!(
                        "<h4>Request body</h4>\n<pre>{}</pre>\n",
                        escape(&redact(&pretty(&request.body)))
                    ));
                }
            }
            BodyMode::Form => {
                let rows: Vec<&KV> = request.form.iter().filter(|kv| kv.enabled).collect();
                if !rows.is_empty() {
                    out.push_str("<h4>Request body</h4>\n<table>\n<thead><tr><th>Field</th><th>Value</th></tr></thead>\n<tbody>\n");
                    for kv in rows {
                        out.push_str(&format!(
                            "<tr><td><code>{}</code></td><td>{}</td></tr>\n",
                            escape(&kv.key),
                            escape(&redact(&kv.value))
                        ));
                    }
                    out.push_str("</tbody>\n</table>\n");
                }
            }
            BodyMode::Multipart => {
                if !request.multipart.is_empty() {
                    out.push_str("<h4>Request body</h4>\n<p class=\"meta-line\">multipart/form-data</p>\n<table>\n<thead><tr><th>Field</th><th>Type</th><th>Value</th></tr></thead>\n<tbody>\n");
                    for field in &request.multipart {
                        out.push_str(&format!(
                            "<tr><td><code>{}</code></td><td>{}</td><td>{}</td></tr>\n",
                            escape(&field.key),
                            if matches!(field.kind, crate::model::FieldKind::File) {
                                "file"
                            } else {
                                "text"
                            },
                            escape(&redact(&field.value))
                        ));
                    }
                    out.push_str("</tbody>\n</table>\n");
                }
            }
            BodyMode::Binary => {
                out.push_str(
                    "<h4>Request body</h4>\n<p class=\"meta-line\">Binary payload sent as the raw request body.</p>\n",
                );
            }
            BodyMode::None => {}
        }
    }

    if options.include_examples && !request.example_body.trim().is_empty() {
        let status = if request.example_status == 0 {
            200
        } else {
            request.example_status
        };
        out.push_str(&format!(
            "<h4>Example response <span class=\"status s-{}\">{status}</span></h4>\n<pre>{}</pre>\n",
            status_class(status),
            escape(&redact(&pretty(&request.example_body)))
        ));
    }

    out.push_str("</article>\n");
    out
}

fn auth_label(auth: &Auth) -> String {
    match auth {
        Auth::Inherit => "Inherited".into(),
        Auth::None => "No auth".into(),
        Auth::Bearer { .. } => "Bearer token".into(),
        Auth::Basic { .. } => "Basic auth".into(),
        Auth::ApiKey { header, .. } => {
            if header.trim().is_empty() {
                "API key".into()
            } else {
                format!("API key in {}", header.trim())
            }
        }
        Auth::OAuth2 {
            grant: crate::model::OAuthGrant::Pkce,
            ..
        } => "OAuth2 (authorization code + PKCE)".into(),
        Auth::OAuth2 { .. } => "OAuth2 (client credentials)".into(),
    }
}

fn collect_secrets(data: &ProjectData) -> Vec<String> {
    let mut secrets: Vec<String> = Vec::new();
    let mut push = |value: &str| {
        let value = value.trim();
        if value.len() >= 4 && !secrets.iter().any(|known| known == value) {
            secrets.push(value.to_string());
        }
    };
    for env in &data.envs {
        push_environment_secrets(env, &mut push);
    }
    for request in data.all_requests() {
        for kv in &request.headers {
            if kv.secret {
                push(&kv.value);
            }
        }
        for kv in &request.params {
            if kv.secret {
                push(&kv.value);
            }
        }
        match &request.auth {
            Auth::Bearer { token } => push(token),
            Auth::Basic { pass, .. } => push(pass),
            Auth::ApiKey { value, .. } => push(value),
            Auth::OAuth2 { client_secret, .. } => push(client_secret),
            Auth::Inherit | Auth::None => {}
        }
    }
    secrets
}

fn push_environment_secrets(env: &Environment, push: &mut impl FnMut(&str)) {
    for var in &env.vars {
        if var.secret {
            push(&var.value);
        }
    }
}

fn resolve(text: &str, variables: &std::collections::HashMap<String, String>) -> String {
    if variables.is_empty() || !text.contains("{{") {
        return text.to_string();
    }
    crate::model::expand_with(text, variables)
}

fn redact_text(text: &str, secrets: &[String]) -> String {
    let mut out = text.to_string();
    for secret in secrets {
        if out.contains(secret.as_str()) {
            out = out.replace(secret.as_str(), "••••");
        }
    }
    out
}

fn unique_anchor(request: &ApiRequest, used: &mut Vec<String>) -> String {
    let mut base: String = request
        .name
        .chars()
        .map(|ch| {
            if ch.is_ascii_alphanumeric() {
                ch.to_ascii_lowercase()
            } else {
                '-'
            }
        })
        .collect();
    while base.contains("--") {
        base = base.replace("--", "-");
    }
    let base = base.trim_matches('-');
    let mut candidate = if base.is_empty() {
        format!("request-{}", request.id)
    } else {
        format!("{base}-{}", request.id)
    };
    let mut bump = 2;
    while used.contains(&candidate) {
        candidate = format!("{base}-{}-{bump}", request.id);
        bump += 1;
    }
    used.push(candidate.clone());
    candidate
}

fn pretty(text: &str) -> String {
    match serde_json::from_str::<serde_json::Value>(text) {
        Ok(value) => serde_json::to_string_pretty(&value).unwrap_or_else(|_| text.to_string()),
        Err(_) => text.to_string(),
    }
}

fn status_class(status: u16) -> &'static str {
    match status {
        200..=299 => "ok",
        300..=399 => "redirect",
        400..=499 => "client",
        _ => "server",
    }
}

pub fn escape(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for ch in text.chars() {
        match ch {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            '\'' => out.push_str("&#39;"),
            other => out.push(other),
        }
    }
    out
}

fn today() -> String {
    let seconds = crate::model::now_secs();
    let days = seconds / 86_400;
    // Civil date from days since the Unix epoch (Howard Hinnant's algorithm).
    let z = days as i64 + 719_468;
    let era = if z >= 0 { z } else { z - 146_096 } / 146_097;
    let doe = z - era * 146_097;
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let y = yoe + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = doy - (153 * mp + 2) / 5 + 1;
    let m = if mp < 10 { mp + 3 } else { mp - 9 };
    let y = if m <= 2 { y + 1 } else { y };
    format!("{y:04}-{m:02}-{d:02}")
}

